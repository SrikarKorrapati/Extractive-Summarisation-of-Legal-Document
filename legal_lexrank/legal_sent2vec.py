"""Raw vectors from the official Indian legal sent2vec binary.

The native binding is optional until uncached text is embedded. Install it from
epfml/sent2vec at SOURCE_REVISION; the similarly named PyPI package is unrelated.
Published Law-AI text vectors differ from direct native inference and must not
be mixed with vectors generated by this adapter.
"""

from functools import lru_cache
import hashlib
import json
import os
from pathlib import Path
import tempfile
from threading import RLock

from filelock import FileLock
import numpy as np


MODEL_ID = "Law-AI/legal-sent2vec-200"
MODEL_URL = "https://cse.iitkgp.ac.in/~saptarshi/models/sent2vec.bin"
BINARY_SHA256 = "1e7f7f1c182a11444085262896ac833243ca4d8bd1f7168446f2219a0be909f0"
BINARY_BYTES = 2_252_249_083
SOURCE_REVISION = "9efbc2dd69f6c737c3a752c9dc5fbb4843d578b6"
DIMENSIONS = 200
DEFAULT_MODEL_PATH = Path(".cache/role-original/sent2vec.bin")
_NATIVE_LOCK = RLock()


def encoder_identity():
    """Return portable identity without accessing the binary or native package."""
    return {
        "model_id": MODEL_ID,
        "model_url": MODEL_URL,
        "binary_sha256": BINARY_SHA256,
        "binary_bytes": BINARY_BYTES,
        "native_source_revision": SOURCE_REVISION,
        "dimensions": DIMENSIONS,
        "preprocessing": "str.strip only; preserve case and punctuation",
        "normalization": "none",
    }


def _file_state(path):
    path = Path(path).resolve()
    try:
        stat = path.stat()
    except FileNotFoundError as error:
        raise FileNotFoundError(
            f"Legal sent2vec binary not found at {path}. Download {MODEL_URL} "
            f"and verify SHA256 {BINARY_SHA256}."
        ) from error
    return str(path), stat.st_size, stat.st_mtime_ns, stat.st_ctime_ns, stat.st_ino


@lru_cache(maxsize=2)
def _verify_binary(state):
    path, size, *_ = state
    if size != BINARY_BYTES:
        raise ValueError(f"Legal sent2vec binary size differs from the official model: {path}")
    with open(path, "rb") as source:
        digest = hashlib.file_digest(source, "sha256").hexdigest()
    if digest != BINARY_SHA256:
        raise ValueError(f"Legal sent2vec binary SHA256 mismatch: {path}")
    if _file_state(path) != state:
        raise ValueError("Legal sent2vec binary changed while being verified")


@lru_cache(maxsize=1)
def _native_model(state):
    _verify_binary(state)
    try:
        import sent2vec
    except ImportError as error:
        raise ImportError(
            "Uncached legal sentence vectors require the native epfml/sent2vec "
            f"binding at commit {SOURCE_REVISION}; do not install the unrelated "
            "PyPI sent2vec package."
        ) from error
    if not hasattr(sent2vec, "Sent2vecModel"):
        raise ImportError("The installed sent2vec package is not the epfml native binding")
    model = sent2vec.Sent2vecModel()
    model.load_model(state[0], inference_mode=True)
    if model.get_emb_size() != DIMENSIONS:
        raise ValueError("The native legal sent2vec model must produce 200-dimensional vectors")
    return model


def _validate_vectors(values, count):
    values = np.asarray(values)
    if (values.dtype != np.float32 or values.shape != (count, DIMENSIONS)
            or not np.isfinite(values).all()):
        raise ValueError("Legal sent2vec vectors must be finite float32 with shape (sentences, 200)")
    # Unknown-word fragments can legitimately produce zero vectors. Keep their
    # rows to preserve sentence/label alignment and document context.
    return values


def sentence_vectors(sentences, cache_dir=Path(".cache/legal_lexrank"), model_path=None):
    """Embed stripped sentences in order, without normalization or tokenization.

    Cache hits need neither the native dependency nor the large binary. For new
    vectors use model_path, LEGAL_SENT2VEC_MODEL, or DEFAULT_MODEL_PATH, in that
    order. The exact official binary is verified before native loading.
    """
    if isinstance(sentences, (str, bytes)):
        raise TypeError("Pass a sequence of sentence strings, not a single string")
    sentences = list(sentences)
    if any(not isinstance(sentence, str) for sentence in sentences):
        raise TypeError("Every sentence must be a string")
    sentences = [sentence.strip() for sentence in sentences]
    if any("\n" in sentence or "\r" in sentence for sentence in sentences):
        raise ValueError("Each sentence must occupy one line; native sent2vec stops at line breaks")
    if not sentences:
        return np.empty((0, DIMENSIONS), dtype=np.float32)
    identity = {"encoder": encoder_identity(), "sentences": sentences}
    digest = hashlib.sha256(json.dumps(
        identity, ensure_ascii=False, sort_keys=True, separators=(",", ":"),
    ).encode("utf-8")).hexdigest()
    directory = Path(cache_dir) / "legal_sent2vec"
    directory.mkdir(parents=True, exist_ok=True)
    cached = directory / f"{digest}.npy"
    with FileLock(str(cached) + ".lock"):
        if cached.exists():
            return _validate_vectors(np.load(cached, allow_pickle=False), len(sentences))
        path = Path(model_path or os.environ.get("LEGAL_SENT2VEC_MODEL") or DEFAULT_MODEL_PATH)
        with _NATIVE_LOCK:
            state = _file_state(path)
            model = _native_model(state)
            values = _validate_vectors(
                model.embed_sentences(sentences, num_threads=1), len(sentences),
            )
            if _file_state(path) != state:
                raise ValueError("Legal sent2vec binary changed during inference")
        with tempfile.NamedTemporaryFile(dir=directory, delete=False) as temporary:
            temporary_path = Path(temporary.name)
            try:
                np.save(temporary, values, allow_pickle=False)
                temporary.flush()
                os.fsync(temporary.fileno())
            except BaseException:
                temporary_path.unlink(missing_ok=True)
                raise
        try:
            os.replace(temporary_path, cached)
        finally:
            temporary_path.unlink(missing_ok=True)
        return values
